from __future__ import annotations

from typing import Protocol
from ..driver import Driver
from ..vehicle import Vehicle
from ..membership import Membership
from ..organization import Organization
from ..connector_type import ConnectorType
from .models import VehicleSnapshot, StationSnapshot


class DriverRepository(Protocol):
    def get(self, driver_id: int) -> Driver | None: ...
    def list(self) -> list[Driver]: ...
    def save(self, driver: Driver) -> Driver: ...
    def delete(self, driver_id: int) -> None: ...


class VehicleRepository(Protocol):
    def get(self, vehicle_id: int) -> VehicleSnapshot | None: ...
    def list(self) -> list[VehicleSnapshot]: ...
    def save(self, vehicle: Vehicle, accepted_connector_ids: list[int]) -> VehicleSnapshot: ...
    def delete(self, vehicle_id: int) -> None: ...


class MembershipRepository(Protocol):
    def get(self, membership_id: int) -> Membership | None: ...
    def list(self, driver_id: int | None = None) -> list[Membership]: ...
    def save(self, membership: Membership) -> Membership: ...
    def delete(self, membership_id: int) -> None: ...


class StationRepository(Protocol):
    def get(self, station_id: int) -> StationSnapshot | None: ...
    def list(self) -> list[StationSnapshot]: ...


class OrganizationRepository(Protocol):
    def get(self, organization_id: int) -> Organization | None: ...
    def list(self) -> list[Organization]: ...


class CatalogRepository(Protocol):
    def connectors(self) -> list[ConnectorType]: ...
    def networks(self) -> list[Organization]: ...


class UnitOfWork(Protocol):
    # 운전자 저장소입니다. 구현체는 작업 하나의 연결 범위 안에서 사용합니다.
    drivers: DriverRepository
    # 차량 본체와 수용 커넥터를 함께 저장하는 저장소입니다.
    vehicles: VehicleRepository
    # 운전자별 네트워크 가입 기간 저장소입니다.
    memberships: MembershipRepository
    # 충전소·포트·시간표·출처를 합쳐 읽는 저장소입니다.
    stations: StationRepository
    # 폼에서 선택할 규격과 네트워크 목록입니다.
    catalog: CatalogRepository
    # 소유자·운영사·네트워크 기관을 읽는 저장소입니다.
    organizations: OrganizationRepository

    def __enter__(self) -> 'UnitOfWork': ...
    def __exit__(self, exc_type, exc_value, traceback) -> None: ...
    def commit(self) -> None: ...
    def rollback(self) -> None: ...
